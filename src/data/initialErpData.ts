/**
 * Recalculates every leaf account balance from posted journal entries,
 * then rolls up balances hierarchically to all parent accounts in Chart of Accounts.
 */
export function recalculateChartBalances(
  accounts: ChartAccount[],
  journalEntries: JournalEntry[]
): ChartAccount[] {
  const leafNet = new Map<string, number>();

  for (const je of journalEntries) {
    if (je.status !== 'posted') continue;
    for (const line of je.lines) {
      const acc = accounts.find((a) => a.id === line.accountId);
      if (!acc) continue;
      const delta =
        acc.normalBalance === 'debit'
          ? line.debit - line.credit
          : line.credit - line.debit;
      leafNet.set(acc.id, (leafNet.get(acc.id) ?? 0) + delta);
    }
  }

  // Build children map for bottom-up roll-up
  const childrenMap = new Map<string, string[]>();
  for (const acc of accounts) {
    if (acc.parentId) {
      const list = childrenMap.get(acc.parentId) ?? [];
      list.push(acc.id);
      childrenMap.set(acc.parentId, list);
    }
  }

  const computed = new Map<string, number>();
  const getAccountTotal = (accountId: string): number => {
    if (computed.has(accountId)) return computed.get(accountId) ?? 0;
    const acc = accounts.find((a) => a.id === accountId);
    if (!acc) return 0;
    const children = childrenMap.get(accountId) ?? [];
    let total = leafNet.get(accountId) ?? 0;
    for (const childId of children) {
      const childAcc = accounts.find((a) => a.id === childId);
      const childVal = getAccountTotal(childId);
      if (childAcc && childAcc.normalBalance === acc.normalBalance) {
        total += childVal;
      } else {
        total -= childVal;
      }
    }
    computed.set(accountId, total);
    return total;
  };

  return accounts.map((acc) => ({
    ...acc,
    currentBalance: getAccountTotal(acc.id),
  }));
}

